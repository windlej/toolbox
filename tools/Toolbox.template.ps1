if ($List) {
    $Script:Toolbox | Sort-Object CategoryName, Name |
        Select-Object @{ n = 'Category'; e = { $_.CategoryName } }, Name, Synopsis |
        Format-Table -AutoSize -Wrap
    return
}

if ($Name) {
    $found = Find-ToolboxEntry $Name
    if ($found.Count -eq 0) { Write-Error "No script named '$Name'. Run with -List to see them."; return }
    if ($found.Count -gt 1) { Write-Error "'$Name' matches more than one script: $($found.Name -join ', ')"; return }
    if ($OutFile) {
        Save-ScriptFile $found[0] $OutFile
        Write-Host "Saved $OutFile"
    } elseif (Copy-ScriptToClipboard $found[0]) {
        Write-Host "Copied $($found[0].Name) to the clipboard."
    } else {
        Write-Error 'No clipboard available. Use -OutFile to write the script to a file.'
    }
    return
}

$banner = "$($Script:Toolbox.Count) scripts | built $Script:ToolboxBuilt"
$categories = @($Script:Toolbox | Group-Object CategoryName | Sort-Object Name)

if (-not (Test-CanReadKeys)) {
    Write-Host 'No interactive keyboard here, using the numbered list. Use -List or -Name for scripted use.' -ForegroundColor Yellow
    $catRows = @($categories | ForEach-Object { [pscustomobject]@{ Label = "$($_.Name) ($($_.Count))"; Payload = $_ } })
    $cat = Show-NumberedPicker 'Category' $catRows
    if (-not $cat) { return }
    $rows = @($cat.Payload.Group | Sort-Object Name | ForEach-Object { [pscustomobject]@{ Label = "$($_.Name) - $($_.Synopsis)"; Entry = $_ } })
    $pick = Show-NumberedPicker $cat.Payload.Name $rows
    if ($pick) {
        if (Copy-ScriptToClipboard $pick.Entry) { Write-Host "Copied $($pick.Entry.Name) to the clipboard." }
        else { $p = Get-FreePath (Get-Location).Path $pick.Entry.Name; Save-ScriptFile $pick.Entry $p; Write-Host "Saved $p" }
    }
    return
}

$catRows = @()
$catRows += [pscustomobject]@{
    Label = "All scripts ($($Script:Toolbox.Count))"; Search = 'all scripts'; Payload = $null
}
foreach ($g in $categories) {
    $catRows += [pscustomobject]@{ Label = "$($g.Name) ($($g.Count))"; Search = $g.Name; Payload = $g }
}

try {
    while ($true) {
        $cat = Show-Picker -Title 'Toolbox: select a category' -Rows $catRows -Banner $banner
        if (-not $cat) { break }
        $pool = if ($cat.Payload) { @($cat.Payload.Group) } else { @($Script:Toolbox) }
        $rows = @($pool | Sort-Object Name | ForEach-Object {
            [pscustomobject]@{
                Label  = "$($_.Name)  -  $($_.Synopsis)"
                Search = "$($_.Name) $($_.Synopsis) $($_.CategoryName) $($_.When)"
                Entry  = $_
            }
        })
        $title = if ($cat.Payload) { $cat.Payload.Name } else { 'All scripts' }
        [void](Show-Picker -Title $title -Rows $rows -Scripts -Banner $banner)
    }
} finally {
    Clear-Host
}
