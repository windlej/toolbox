function Show-Picker {
    <#
    Rows are objects with Label, Search, Entry (script) or Payload (anything). When -Scripts is set, Enter copies
    and Tab saves, and the detail pane describes the highlighted script. Otherwise Enter returns the row.
    Returns the chosen row, or $null for Back/Esc.
    #>
    param(
        [string]$Title,
        [object[]]$Rows,
        [switch]$Scripts,
        [string]$Banner
    )

    $filter = ''; $sel = 0; $top = 0; $prev = 0; $status = $null
    Clear-Host
    while ($true) {
        $view = if ($filter) {
            @($Rows | Where-Object { $_.Search.IndexOf($filter, [StringComparison]::OrdinalIgnoreCase) -ge 0 })
        } else { @($Rows) }
        if ($sel -ge $view.Count) { $sel = [Math]::Max(0, $view.Count - 1) }

        $w = Get-ConsoleWidth; $h = Get-ConsoleHeight
        $detail = @()
        if ($Scripts -and $view.Count -gt 0) { $detail = @(Get-DetailLine $view[$sel].Entry $w) }
        $listH = [Math]::Max(3, $h - ($detail.Count + 7))
        if ($sel -lt $top) { $top = $sel }
        if ($sel -ge ($top + $listH)) { $top = $sel - $listH + 1 }
        if ($top -lt 0) { $top = 0 }

        $out = New-Object System.Collections.Generic.List[object]
        $out.Add(@{ T = "  $Title"; C = 'White' })
        if ($Banner) { $out.Add(@{ T = "  $Banner"; C = 'DarkGray' }) } else { $out.Add(@{ T = ''; C = 'Gray' }) }
        $out.Add(@{ T = ('-' * $w); C = 'DarkGray' })
        if ($view.Count -eq 0) {
            $out.Add(@{ T = '   (nothing matches the filter)'; C = 'Yellow' })
        } else {
            $last = [Math]::Min($view.Count - 1, $top + $listH - 1)
            for ($i = $top; $i -le $last; $i++) {
                $mark = if ($i -eq $sel) { ' > ' } else { '   ' }
                $out.Add(@{ T = ($mark + $view[$i].Label); C = $(if ($i -eq $sel) { 'Cyan' } else { 'Gray' }) })
            }
        }
        if ($Scripts) {
            $out.Add(@{ T = ('-' * $w); C = 'DarkGray' })
            foreach ($d in $detail) { $out.Add(@{ T = $d; C = 'DarkGray' }) }
        }
        $out.Add(@{ T = ('-' * $w); C = 'DarkGray' })
        if ($status) {
            $out.Add(@{ T = "  $($status.Text)"; C = $(if ($status.Ok) { 'Green' } else { 'Red' }) })
        } else {
            $keys = if ($Scripts) { 'Enter copy | F2 copy as scriptblock | Tab save | type to filter | Esc back' } else { 'Enter open | type to filter | Esc quit' }
            $f = if ($filter) { "   filter: $filter   ($($view.Count) match)" } else { '' }
            $out.Add(@{ T = "  $keys$f"; C = 'DarkGray' })
        }

        [Console]::SetCursorPosition(0, 0)
        foreach ($l in $out) {
            $t = [string]$l.T
            if ($t.Length -gt $w) { $t = $t.Substring(0, $w - 3) + '...' }
            Write-Host $t.PadRight($w) -ForegroundColor $l.C
        }
        for ($i = $out.Count; $i -lt $prev; $i++) { Write-Host (' ' * $w) }
        $prev = $out.Count
        $status = $null

        $key = [Console]::ReadKey($true)
        switch ($key.Key) {
            'UpArrow'    { if ($sel -gt 0) { $sel-- } }
            'DownArrow'  { if ($sel -lt $view.Count - 1) { $sel++ } }
            'PageUp'     { $sel = [Math]::Max(0, $sel - $listH) }
            'PageDown'   { $sel = [Math]::Min([Math]::Max(0, $view.Count - 1), $sel + $listH) }
            'Home'       { $sel = 0 }
            'End'        { $sel = [Math]::Max(0, $view.Count - 1) }
            'Backspace'  { if ($filter) { $filter = $filter.Substring(0, $filter.Length - 1); $sel = 0; $top = 0 } }
            'Escape'     { if ($filter) { $filter = ''; $sel = 0; $top = 0 } else { return $null } }
            'Enter' {
                if ($view.Count -gt 0) {
                    if ($Scripts) { $status = Invoke-EntryAction $view[$sel].Entry 'Copy' } else { return $view[$sel] }
                }
            }
            'F2' {
                if ($Scripts -and $view.Count -gt 0) { $status = Invoke-EntryAction $view[$sel].Entry 'Block' }
            }
            'Tab' {
                if ($Scripts -and $view.Count -gt 0) { $status = Invoke-EntryAction $view[$sel].Entry 'Save' }
            }
            default {
                $c = $key.KeyChar
                if ($c -and -not [char]::IsControl($c)) { $filter += $c; $sel = 0; $top = 0 }
            }
        }
    }
}

function Show-NumberedPicker {
    # Fallback when keys cannot be read (redirected input, some hosts): numbered list, type a number to copy.
    param([string]$Title, [object[]]$Rows)
    while ($true) {
        Write-Host "`n  $Title" -ForegroundColor White
        for ($i = 0; $i -lt $Rows.Count; $i++) { Write-Host ("  {0,3}) {1}" -f ($i + 1), $Rows[$i].Label) }
        $answer = Read-Host "Number to select, blank to go back"
        if (-not $answer) { return $null }
        if ($answer -match '^\d+$' -and [int]$answer -ge 1 -and [int]$answer -le $Rows.Count) { return $Rows[[int]$answer - 1] }
        Write-Host '  Not a valid number.' -ForegroundColor Yellow
    }
}

function Find-ToolboxEntry {
    param([string]$Wanted)
    $stem = [IO.Path]::GetFileNameWithoutExtension($Wanted)
    @($Script:Toolbox | Where-Object {
        $_.Name -ieq $Wanted -or [IO.Path]::GetFileNameWithoutExtension($_.Name) -ieq $stem
    })
}

