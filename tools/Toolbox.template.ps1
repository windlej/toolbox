function Get-ConsoleWidth {
    try {
        $w = [Console]::WindowWidth
        if ($w -lt 41) { return 80 }
        return [Math]::Min(($w - 1), 120)
    } catch { return 80 }
}

function Get-ConsoleHeight {
    try {
        $h = [Console]::WindowHeight
        if ($h -lt 15) { return 30 }
        return $h
    } catch { return 30 }
}

function Test-CanReadKeys {
    try { return (-not [Console]::IsInputRedirected) -and (-not [Console]::IsOutputRedirected) } catch { return $false }
}

function Get-ScriptText {
    param([Parameter(Mandatory)][psobject]$Entry)
    $bytes = [Convert]::FromBase64String($Entry.Data)
    $in = New-Object System.IO.MemoryStream (, $bytes)
    $gz = New-Object System.IO.Compression.GZipStream ($in, [System.IO.Compression.CompressionMode]::Decompress)
    $reader = New-Object System.IO.StreamReader ($gz, (New-Object System.Text.UTF8Encoding $false))
    try { return $reader.ReadToEnd() } finally { $reader.Dispose() }
}

function Get-WrappedLine {
    # "Label        text..." wrapped to Width, continuation lines indented under the text.
    param([string]$Label, [string]$Text, [int]$Width)
    $indent = 15
    $room = [Math]::Max(20, $Width - $indent)
    $out = New-Object System.Collections.Generic.List[string]
    $line = ''
    foreach ($word in ($Text -split '\s+')) {
        if (-not $word) { continue }
        if ($line -and (($line.Length + 1 + $word.Length) -gt $room)) {
            $out.Add($line)
            $line = $word
        } elseif ($line) {
            $line = "$line $word"
        } else {
            $line = $word
        }
    }
    if ($line) { $out.Add($line) }
    if ($out.Count -eq 0) { return @() }
    $result = @()
    for ($i = 0; $i -lt $out.Count; $i++) {
        $prefix = if ($i -eq 0) { ("  " + $Label).PadRight($indent) } else { ' ' * $indent }
        $result += ($prefix + $out[$i])
    }
    return $result
}

function Get-DetailLine {
    param([psobject]$Entry, [int]$Width)
    $lines = @()
    $lines += Get-WrappedLine 'What' $Entry.Synopsis $Width
    if ($Entry.When)     { $lines += Get-WrappedLine 'When to use' $Entry.When $Width }
    if ($Entry.Safety)   { $lines += Get-WrappedLine 'Safety' $Entry.Safety $Width }
    if ($Entry.Perms)    { $lines += Get-WrappedLine 'Permissions' $Entry.Perms $Width }
    if ($Entry.Platform) { $lines += Get-WrappedLine 'Platform' $Entry.Platform $Width }
    if ($Entry.Modules)  { $lines += Get-WrappedLine 'Modules' $Entry.Modules $Width }
    if ($Entry.Params.Count -gt 0) { $lines += Get-WrappedLine 'Parameters' ($Entry.Params -join ', ') $Width }
    if ($Entry.Example)  { $lines += Get-WrappedLine 'Example' $Entry.Example $Width }
    if ($lines.Count -gt 12) { $lines = @($lines[0..10]) + '               ...' }
    return $lines
}

function Save-ScriptFile {
    param([psobject]$Entry, [string]$Path)
    $text = Get-ScriptText $Entry
    # PowerShell 5.1 reads a BOM-less file as ANSI, so .ps1 gets a BOM; bash/Python must not have one.
    $bom = $Entry.Name -like '*.ps1'
    $enc = New-Object System.Text.UTF8Encoding $bom
    [System.IO.File]::WriteAllText($Path, $text, $enc)
}

function Get-BlockVariable {
    param([psobject]$Entry)
    '$' + ([IO.Path]::GetFileNameWithoutExtension($Entry.Name) -replace '[^A-Za-z0-9]', '_')
}

function Copy-ScriptToClipboard {
    # Returns $true when the text reached the clipboard. -AsBlock wraps a PowerShell script as
    # "$Name = { ... }" so pasting it into a console defines it; run it with: & $Name -Param value
    param([psobject]$Entry, [switch]$AsBlock)
    $text = Get-ScriptText $Entry
    if ($AsBlock) { $text = "$(Get-BlockVariable $Entry) = {`r`n$text`r`n}`r`n" }
    try {
        if (Get-Command Set-Clipboard -ErrorAction SilentlyContinue) {
            Set-Clipboard -Value $text
            return $true
        }
        if (Get-Command pbcopy -ErrorAction SilentlyContinue) { $text | & pbcopy; return $true }
        if (Get-Command xclip -ErrorAction SilentlyContinue)  { $text | & xclip -selection clipboard; return $true }
    } catch { }
    return $false
}

function Get-FreePath {
    param([string]$Folder, [string]$FileName)
    $path = Join-Path $Folder $FileName
    if (-not (Test-Path -LiteralPath $path)) { return $path }
    $base = [IO.Path]::GetFileNameWithoutExtension($FileName)
    $ext = [IO.Path]::GetExtension($FileName)
    $n = 1
    while (Test-Path -LiteralPath (Join-Path $Folder "$base-$n$ext")) { $n++ }
    return (Join-Path $Folder "$base-$n$ext")
}

function Invoke-EntryAction {
    # Enter = copy, Tab = save. Returns a status line for the picker footer.
    param([psobject]$Entry, [ValidateSet('Copy', 'Block', 'Save')][string]$Mode)
    if ($Mode -eq 'Block') {
        if ($Entry.Kind -ne 'PowerShell') {
            return @{ Ok = $false; Text = 'Scriptblock copy is for PowerShell scripts only. Use Enter to copy the text.' }
        }
        if (Copy-ScriptToClipboard $Entry -AsBlock) {
            $v = Get-BlockVariable $Entry
            return @{ Ok = $true; Text = "Copied as scriptblock. Paste it, then run:  & $v -Param value" }
        }
        $Mode = 'Save'
    }
    if ($Mode -eq 'Copy') {
        if (Copy-ScriptToClipboard $Entry) {
            return @{ Ok = $true; Text = "Copied $($Entry.Name) ($($Entry.Lines) lines) to the clipboard. Paste it into a file or console." }
        }
        $Mode = 'Save'
    }
    $path = Get-FreePath (Get-Location).Path $Entry.Name
    try {
        Save-ScriptFile $Entry $path
        return @{ Ok = $true; Text = "Saved $path" }
    } catch {
        return @{ Ok = $false; Text = "Could not save $path : $($_.Exception.Message)" }
    }
}

