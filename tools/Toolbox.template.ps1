#Requires -Version 5.1

<#
.SYNOPSIS
Toolbox picker: browse the script library, read what each script does, and copy one out.

.DESCRIPTION
Single self-contained file. Every script in the library is embedded in it together with its description, so it
works on a machine that does not have the repository (a jumpbox, a customer server). Pick a category, move
through the list to read the details, and press Enter to copy the selected script to the clipboard. Nothing is
run and nothing is installed. Paste the script into a .ps1 file (or press Tab to save it as a file) and run it
from there.

Keys: Up/Down/PageUp/PageDown move, Enter copies the script, F2 copies it as a scriptblock you can paste straight
into a console and run with & $Name -Param value, Tab saves it to a file, typing filters the list,
Backspace edits the filter, Esc clears the filter or goes back.

Generated by tools/Build-Toolbox.ps1. Do not edit the generated file; edit tools/Toolbox.template.ps1 or the
script headers and rebuild.

.PARAMETER List
Print the catalog (name, category, synopsis) and exit. Useful when the interactive picker is not available.

.PARAMETER Name
Copy (or with -OutFile, save) one script by name without opening the picker. Accepts the name with or without
its extension.

.PARAMETER OutFile
Used with -Name: write the script to this path instead of the clipboard.

.EXAMPLE
.\toolbox.ps1

.EXAMPLE
.\toolbox.ps1 -List

.EXAMPLE
.\toolbox.ps1 -Name Get-StaleUserAccount -OutFile C:\Temp\Get-StaleUserAccount.ps1

.NOTES
Platform:     Windows PowerShell 5.1 or PowerShell 7 (Windows, macOS, Linux)
Permissions:  None (reads nothing from disk; writes a file only when you save one)
When to use:  On a jumpbox or customer machine that has no copy of the repository.
Safety:       Read-only (copies text to the clipboard or writes the file you ask for)
Version:      2.0
#>
[CmdletBinding()]
param(
    [switch]$List,
    [string]$Name,
    [string]$OutFile
)

Set-StrictMode -Version Latest

